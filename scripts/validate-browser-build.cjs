const fs=require('node:fs'),path=require('node:path');
const [directory]=process.argv.slice(2);
if(!directory)throw new Error('Pass the compiled browser directory');
const manifest=JSON.parse(fs.readFileSync(path.join(directory,'browser-build.json'),'utf8'));
if(manifest.formatVersion!==1||!Number.isInteger(manifest.browserApiProtocol)||manifest.browserApiProtocol<1||!Number.isInteger(manifest.coreApiProtocol)||manifest.coreApiProtocol<1||typeof manifest.appVersion!=='string'||!manifest.appVersion||!/^[0-9a-f]{40,64}$/.test(manifest.desktopCommit||''))throw new Error('Invalid browser build manifest');
const html=fs.readFileSync(path.join(directory,'index.html'),'utf8');
const entry=/src="\.\/(assets\/[^" ]+\.js)"/.exec(html)?.[1];
if(!entry)throw new Error('Browser module entry missing');
const bundle=fs.readFileSync(path.join(directory,entry),'utf8');
if(!bundle.includes('remote_protocol_mismatch'))throw new Error('Not the Remote browser entry');
const {createHash}=require('node:crypto');
if(manifest.entry?.path!==entry||createHash('sha256').update(bundle).digest('hex')!==manifest.entry.sha256)throw new Error('Browser entry does not match its build manifest');
console.log('Browser API '+manifest.browserApiProtocol+', core API '+manifest.coreApiProtocol+', desktop '+manifest.desktopCommit);
